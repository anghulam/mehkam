/**
 * includes/version.php — رقم إصدار المنصة وسجلّ التحديثات
 *
 * الإصدار الظاهر = MEHKAM_BASE_VERSION (رئيسي.فرعي — يُعدَّل يدوياً عند إطلاق ميزات كبيرة)
 *                  + رقم البناء التلقائي الذي يكتبه النشر (GitHub Actions) في includes/build.php
 *                    عند كل تحديث يُدمج في main، فيتغيّر الإصدار تلقائياً مع كل تحديث.
 *
 * دليل المستخدم (PDF) يعتمد على هذا الإصدار: أي تغيّر فيه يُعيد توليد الدليل تلقائياً.
 */

if (!defined('MEHKAM_BASE_VERSION')) define('MEHKAM_BASE_VERSION', '1.0');

// يولّده النشر التلقائي: MEHKAM_BUILD_NUMBER (عدد الـ commits)، MEHKAM_BUILD_SHA، MEHKAM_BUILD_DATE
if (!defined('MEHKAM_BUILD_NUMBER') && is_file(__DIR__ . '/build.php')) {
    @include __DIR__ . '/build.php';
}

/** مصفوفة معلومات الإصدار: version / base / build / sha / date */
function mehkam_version_info(): array {
    $build = defined('MEHKAM_BUILD_NUMBER') ? (int)MEHKAM_BUILD_NUMBER : 0;
    return [
        'base'    => MEHKAM_BASE_VERSION,
        'build'   => $build,
        'version' => MEHKAM_BASE_VERSION . '.' . $build,
        'sha'     => defined('MEHKAM_BUILD_SHA')  ? (string)MEHKAM_BUILD_SHA  : '',
        'date'    => defined('MEHKAM_BUILD_DATE') ? (string)MEHKAM_BUILD_DATE : '',
    ];
}

/** الإصدار كنص: 1.0.123 */
function mehkam_version(): string {
    return mehkam_version_info()['version'];
}

