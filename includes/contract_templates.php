/** استبدال متغيّرات القالب */
function contract_fill_vars($text, array $vars) {
    $map = [
        '{{office_name}}' => $vars['office_name'] ?? '',
        '{{client_name}}' => $vars['client_name'] ?? '.........',
        '{{today}}'       => $vars['today'] ?? date('Y/m/d'),
        '{{value}}'       => $vars['value'] ?? '.........',
    ];
    return strtr((string) $text, $map);
}

